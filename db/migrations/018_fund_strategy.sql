-- 출자기관 공고는 분야별 모집 부문(초기 · 성장 · 세컨더리 · 해외 · 기타)으로 나뉜다. 공고에 지원할 때
-- 조합 분야와 부문 분야가 같아야 한다. LP ERP는 연동 조합의 분야를 이 값으로 받는다 (그동안은 LP 담당자가 넣었다)
-- · 분류는 LP ERP와 같다 (🔗 LP lib/labels.ts STRATEGIES) ⚠️ 기관마다 분류가 다를 수 있다
-- · 이미 있는 조합은 '기타'로 채운다. 데모 조합의 실제 분야는 데모 시드가 넣는다
-- =============================================================================

alter table funds add column strategy text not null default 'other'
  check (strategy in ('early', 'growth', 'secondary', 'overseas', 'other'));
comment on column funds.strategy is '조합 분야 — 출자기관 공고 부문과 맞춰 본다, LP ERP에 내보낸다 (D47)';
