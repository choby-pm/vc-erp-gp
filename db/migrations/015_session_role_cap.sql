-- =============================================================================
-- 015_session_role_cap.sql — 세션 단위 권한 제한 (D43)
-- =============================================================================
-- 배포된 사이트(공개 주소)의 "데모 계정으로 둘러보기"는 누구나 누를 수 있다.
-- 데모 계정 자체는 관리자라(로컬 개발·시연용), 배포 환경에서 데모 버튼으로 만든 세션만 조회 전용으로 제한한다.
-- 로컬과 배포가 같은 DB를 쓰므로 계정의 역할을 바꾸지 않고 세션에 상한을 둔다.
-- =============================================================================

alter table sessions add column role_cap text check (role_cap in ('viewer'));
comment on column sessions.role_cap is '이 세션의 권한 상한. viewer 면 계정 역할과 관계없이 조회만 (배포 환경 데모 로그인)';
